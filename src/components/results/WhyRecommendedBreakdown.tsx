import React from 'react';
import { RecommendationResult } from '../../types/analysis';
import { Card } from '../ui/Card';
import { SCORING_WEIGHTS, FACTOR_LABELS } from '../../services/recommendationEngine';
import { CheckCircle2, HelpCircle, BarChart3 } from 'lucide-react';

export interface WhyRecommendedBreakdownProps {
  result: RecommendationResult;
}

export const WhyRecommendedBreakdown: React.FC<WhyRecommendedBreakdownProps> = ({ result }) => {
  const breakdown = result.scores.find((s) => s.slug === result.materialSlug)?.breakdown || {};

  return (
    <div className="grid grid-cols-1 lg:grid-cols-2 gap-6">
      {/* Dynamic Factor Contributions */}
      <Card className="p-6 space-y-4">
        <div className="flex items-center justify-between border-b border-slate-200 dark:border-slate-800 pb-3">
          <div className="flex items-center gap-2">
            <BarChart3 className="w-4 h-4 text-emerald-500" />
            <h3 className="text-sm font-bold text-slate-900 dark:text-slate-100 font-display">
              Weighted Factor Contributions
            </h3>
          </div>
          <span className="text-[11px] font-mono text-slate-400">Model Weights</span>
        </div>

        <p className="text-xs text-slate-500 dark:text-slate-400">
          The compatibility score is computed by matching material barrier properties against your product's chemical constraints:
        </p>

        <div className="space-y-3 pt-1">
          {Object.entries(SCORING_WEIGHTS).map(([key, weight]) => {
            const rawScore = breakdown[key] ?? 0.8;
            const pointsMax = Math.round(weight * 100);
            const pointsEarned = Math.round(rawScore * pointsMax);
            const pct = Math.min(100, Math.round((pointsEarned / (pointsMax || 1)) * 100));

            return (
              <div key={key} className="space-y-1">
                <div className="flex items-center justify-between text-xs">
                  <span className="font-semibold text-slate-700 dark:text-slate-300">
                    {FACTOR_LABELS[key as keyof typeof FACTOR_LABELS]}
                  </span>
                  <span className="font-mono text-[11px] font-bold text-slate-800 dark:text-slate-200">
                    {pointsEarned} / {pointsMax} pts ({pct}%)
                  </span>
                </div>
                <div className="w-full bg-slate-100 dark:bg-slate-800 h-2 rounded-full overflow-hidden">
                  <div
                    className={`h-full rounded-full transition-all duration-700 ${
                      pct >= 90
                        ? 'bg-emerald-500'
                        : pct >= 70
                        ? 'bg-cyan-500'
                        : pct >= 50
                        ? 'bg-amber-500'
                        : 'bg-rose-500'
                    }`}
                    style={{ width: `${pct}%` }}
                  />
                </div>
              </div>
            );
          })}
        </div>
      </Card>

      {/* Engineering Selection Justifications */}
      <Card className="p-6 space-y-4">
        <div className="flex items-center justify-between border-b border-slate-200 dark:border-slate-800 pb-3">
          <div className="flex items-center gap-2">
            <CheckCircle2 className="w-4 h-4 text-emerald-500" />
            <h3 className="text-sm font-bold text-slate-900 dark:text-slate-100 font-display">
              Why was this packaging recommended?
            </h3>
          </div>
          <span className="text-[11px] text-emerald-600 dark:text-emerald-400 font-semibold">
            {result.reasons.length} Validation Rules Passed
          </span>
        </div>

        <p className="text-xs text-slate-500 dark:text-slate-400">
          Rule-based rationale generated by evaluating your target shelf-life, temperature stability, and permeability:
        </p>

        <div className="space-y-2.5 pt-1">
          {result.reasons.map((reason, idx) => (
            <div
              key={idx}
              className="flex items-start gap-3 p-3 rounded-xl bg-slate-50/80 dark:bg-slate-800/40 border border-slate-200/60 dark:border-slate-700/60"
            >
              <div className="w-5 h-5 rounded-full bg-emerald-100 dark:bg-emerald-900/60 text-emerald-600 dark:text-emerald-300 flex items-center justify-center shrink-0 text-xs font-bold mt-0.5">
                ✓
              </div>
              <p className="text-xs font-medium text-slate-800 dark:text-slate-200 leading-relaxed">
                {reason}
              </p>
            </div>
          ))}
        </div>
      </Card>
    </div>
  );
};
